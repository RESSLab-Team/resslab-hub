"""Pure-unit tests for the ductile-fracture specimen drawings (no database).

matplotlib lives in the optional ``figures`` dependency group (the drawings are
regenerated by hand, not at run time), so these skip where it is absent — as in
CI, which syncs without that group.
"""

import pytest

pytest.importorskip("matplotlib")

from data.fracture_figures_lib import (  # noqa: E402
    SPECIMEN_COLUMNS,
    render_specimen_svg,
)

CNT_ROW = {
    "specimen_type": "CNT",
    "gauge_length": "20",
    "nom_notch_radius": "3",
    "nom_whole_diameter_cnt": "8",
    "nom_notch_diameter_cnt": "5",
}
GP_ROW = {
    "specimen_type": "GP",
    "gauge_length": "20",
    "nom_notch_radius": "1.2",
    "nom_width_gp": "25",
    "nom_whole_thickness_gp": "12",
    "nom_notch_thickness_gp": "2.6",
}


class TestRenderSpecimenSvg:
    def test_draws_a_notched_bar(self):
        svg = render_specimen_svg(CNT_ROW)
        assert svg.startswith("<?xml")
        assert "<svg" in svg
        # The notch dimensions are annotated on the drawing.
        assert "D_" in svg or "path" in svg

    def test_draws_a_grooved_plate(self):
        assert "<svg" in render_specimen_svg(GP_ROW)

    def test_is_reproducible(self):
        # The SVGs are committed, so an unchanged row has to redraw identically.
        assert render_specimen_svg(CNT_ROW) == render_specimen_svg(CNT_ROW)

    def test_rejects_an_unknown_geometry(self):
        with pytest.raises(ValueError, match="unknown specimen_type"):
            render_specimen_svg({**CNT_ROW, "specimen_type": "DEMO-SPEC-01"})

    def test_rejects_a_missing_dimension(self):
        # The data repo writes absent measurements as "NA".
        with pytest.raises(ValueError, match="nom_notch_radius"):
            render_specimen_svg({**CNT_ROW, "nom_notch_radius": "NA"})

    def test_every_geometry_is_drawable(self):
        assert set(SPECIMEN_COLUMNS) == {"CNT", "GP"}
