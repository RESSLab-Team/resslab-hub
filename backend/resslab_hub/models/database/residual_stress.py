"""
Material Database Models
"""

from sqlalchemy import (
    BigInteger,
    Column,
    Float,
    ForeignKey,
    Numeric,
    SmallInteger,
    String,
    cast,
    text,
)
from sqlalchemy.orm import column_property

from resslab_hub.models.database.common import DecimalFloat
from resslab_hub.utils.database import Base


class ResidualStressQPCoefficient(Base):  # type: ignore
    __tablename__ = "residual_stress_qp_coefficient"

    residual_stress_id = Column(
        String, ForeignKey("residual_stress.id"), primary_key=True, index=True
    )
    id = Column(BigInteger, primary_key=True, autoincrement=True)

    qp_coefficient = Column(Numeric, nullable=False)


class ResidualStressDistributionF1(Base):  # type: ignore
    __tablename__ = "residual_stress_distribution_f1"

    residual_stress_id = Column(
        String, ForeignKey("residual_stress.id"), primary_key=True, index=True
    )
    id = Column(BigInteger, primary_key=True, autoincrement=True)

    coordinate = Column(Numeric, nullable=False)
    residual_stress = Column(Numeric, nullable=False)


class ResidualStressDistributionF2(Base):  # type: ignore
    __tablename__ = "residual_stress_distribution_f2"

    residual_stress_id = Column(
        String, ForeignKey("residual_stress.id"), primary_key=True, index=True
    )
    id = Column(BigInteger, primary_key=True, autoincrement=True)

    coordinate = Column(Numeric, nullable=False)
    residual_stress = Column(Numeric, nullable=False)


class ResidualStressDistributionW1(Base):  # type: ignore
    __tablename__ = "residual_stress_distribution_w1"

    residual_stress_id = Column(
        String, ForeignKey("residual_stress.id"), primary_key=True, index=True
    )
    id = Column(BigInteger, primary_key=True, autoincrement=True)

    coordinate = Column(Numeric, nullable=False)
    residual_stress = Column(Numeric, nullable=False)


class ResidualStress(Base):  # type: ignore
    """
    Columns are generated by data.analyzer
    """

    __tablename__ = "residual_stress"

    # START_OF_GENERATED_CODE
    id = Column(String, primary_key=True)
    experimental_program = Column(String, nullable=False)
    date = Column(SmallInteger, nullable=False)
    profile_type = Column(String, nullable=False)
    profile = Column(String, nullable=False)
    spec_var = Column(String, nullable=True)
    steel = Column(String, nullable=False)
    fy_n = Column(DecimalFloat, nullable=True)
    fy_e = Column(DecimalFloat, nullable=True)
    fy_mf = Column(DecimalFloat, nullable=True)
    fy_mw = Column(DecimalFloat, nullable=True)
    h = Column(DecimalFloat, nullable=True)
    b = Column(DecimalFloat, nullable=True)
    tw = Column(DecimalFloat, nullable=True)
    tf = Column(DecimalFloat, nullable=True)
    r = Column(DecimalFloat, nullable=True)
    A = Column(DecimalFloat, nullable=True)
    sigma_0_f = Column(Numeric, nullable=False)
    sigma_0_w = Column(Numeric, nullable=False)
    flange_nr_data = Column(SmallInteger, nullable=False)
    plot_sf = Column(Numeric, nullable=False)
    reference = Column(String, nullable=False)
    link = Column(String, nullable=True)
    latitude = Column(Numeric, nullable=True)
    longitude = Column(Numeric, nullable=True)
    # END_OF_GENERATED_CODE

    # 0/1 "has data" flags, recomputed by recompute_count_flags() at the end
    # of every upload (see resslab_hub/data/count_flags.py).
    qp_coefficient_count = Column(
        SmallInteger, nullable=False, server_default=text("0")
    )
    distribution_F1_count = Column(
        SmallInteger, nullable=False, server_default=text("0")
    )
    distribution_F2_count = Column(
        SmallInteger, nullable=False, server_default=text("0")
    )
    distribution_W1_count = Column(
        SmallInteger, nullable=False, server_default=text("0")
    )
    h_over_b = column_property(cast(h, Float) / cast(b, Float))
