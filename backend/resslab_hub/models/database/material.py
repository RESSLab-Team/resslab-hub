    uvc_a = Column(Numeric, nullable=False)
    uvc_c1__mpa_ = Column(Numeric, nullable=False)
    uvc_g1 = Column(Numeric, nullable=False)
    uvc_c2__mpa_ = Column(Numeric, nullable=False)
    uvc_g2 = Column(Numeric, nullable=False)
    hidden_dataset_index = Column(SmallInteger, nullable=False)
    uvc_sigma_sat__mpa_ = Column(Numeric, nullable=False)
    uvc_sigma_hard__mpa_ = Column(Numeric, nullable=False)
    uvc_rho_yield = Column(Numeric, nullable=False)
    uvc_rho_iso = Column(Numeric, nullable=False)
    uvc_rho_kin = Column(Numeric, nullable=False)
    uvc_rho_d = Column(Numeric, nullable=False)

    type = column_property(grade + text("'-'") + spec)

    year = column_property(func.extract("year", date))

    stress_strain_count = column_property(
        select(func.count(MaterialStressStrain.id))
        .where(MaterialStressStrain.material_id == id)
        .correlate_except(MaterialStressStrain)
        .scalar_subquery()  # type: ignore
    )
