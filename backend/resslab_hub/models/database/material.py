"""
Material Database Models
"""
from sqlalchemy import (
    BigInteger,
    Column,
    ForeignKey,
    Numeric,
    SmallInteger,
    String,
    func,
    select,
    text,
)
from sqlalchemy.orm import column_property

from resslab_hub.models.database.common import DecimalFloat
from resslab_hub.utils.database import Base


class MaterialStressStrain(Base):  # type: ignore
    __tablename__ = "material_stress_strain"

    material_id = Column(
        String, ForeignKey("material.id"), primary_key=True, index=True
    )
    id = Column(BigInteger, primary_key=True, autoincrement=True)

    stress = Column(Numeric, nullable=False)
    strain = Column(Numeric, nullable=False)


class Material(Base):  # type: ignore
    """
    Columns are generated by data.analyzer
    """

    __tablename__ = "material"

    hidden_index = Column(SmallInteger, nullable=False)
    experimental_program = Column(String, nullable=False)
    id = Column(String, primary_key=True)
    profile_type = Column(String, nullable=False)
    profile = Column(String, nullable=False)
    source = Column(String, nullable=False)
    thickness = Column(Numeric, nullable=False)
    grade = Column(String, nullable=False)
    spec = Column(String)
    lp = Column(String, nullable=False)
    size = Column(String, nullable=False)
    gage_length__mm_ = Column(SmallInteger, nullable=False)
    avg_reduced_dia__mm_ = Column(Numeric, nullable=False)
    avg_fractured_dia_top__mm_ = Column(Numeric)
    avg_fractured_dia_bot__mm_ = Column(Numeric)
    fy_n__mpa_ = Column(SmallInteger, nullable=False)
    fu_n__mpa_ = Column(SmallInteger, nullable=False)
    t_a__deg_c_ = Column(DecimalFloat, nullable=False)
    date = Column(String, nullable=False)
    investigator = Column(String, nullable=False)
    location = Column(String, nullable=False)
    machine = Column(String, nullable=False)
    pid_force_k_p = Column(DecimalFloat, nullable=False)
    pid_force_t_i = Column(DecimalFloat, nullable=False)
    pid_force_t_d = Column(DecimalFloat, nullable=False)
    pid_disp_k_p = Column(DecimalFloat, nullable=False)
    pid_disp_t_i = Column(DecimalFloat, nullable=False)
    pid_disp_t_d = Column(DecimalFloat, nullable=False)
    pid_extenso_k_p = Column(DecimalFloat, nullable=False)
    pid_extenso_t_i = Column(DecimalFloat, nullable=False)
    pid_extenso_t_d = Column(DecimalFloat, nullable=False)
    yield_stress__mpa_ = Column(DecimalFloat, nullable=False)
    elastic_modulus__mpa_ = Column(DecimalFloat, nullable=False)
    fracture_strain = Column(DecimalFloat)
    c = Column(DecimalFloat, nullable=False)
    si = Column(DecimalFloat, nullable=False)
    mn = Column(DecimalFloat, nullable=False)
    p = Column(DecimalFloat, nullable=False)
    s = Column(DecimalFloat, nullable=False)
    n = Column(DecimalFloat)
    cu = Column(DecimalFloat)
    mo = Column(DecimalFloat, nullable=False)
    ni = Column(DecimalFloat, nullable=False)
    cr = Column(DecimalFloat, nullable=False)
    v = Column(DecimalFloat)
    nb = Column(DecimalFloat)
    ti = Column(DecimalFloat)
    al = Column(DecimalFloat, nullable=False)
    b = Column(DecimalFloat)
    zr = Column(DecimalFloat)
    sn = Column(DecimalFloat)
    ca = Column(DecimalFloat)
    h = Column(DecimalFloat)
    fe = Column(DecimalFloat)
    file = Column(String, nullable=False)
    reference = Column(String, nullable=False)
    link = Column(String)
    latitude = Column(Numeric, nullable=False)
    longitude = Column(Numeric, nullable=False)
    citekey = Column(String, nullable=False)
    uvc_phi__prct_ = Column(Numeric, nullable=False)
    uvc_e__mpa_ = Column(Numeric, nullable=False)
    uvc_sigma__mpa_ = Column(Numeric, nullable=False)
